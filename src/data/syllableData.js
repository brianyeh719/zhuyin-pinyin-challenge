/** 本身就能成音的聲母（空韻）：ㄓ ㄔ ㄕ ㄖ ㄗ ㄘ ㄙ → zhi chi shi ri zi ci si */
const EMPTY_RHYME_INITIALS = ['ㄓ', 'ㄔ', 'ㄕ', 'ㄖ', 'ㄗ', 'ㄘ', 'ㄙ'];

const FINAL_PINYIN = {
  ㄧ: 'i', ㄨ: 'u', ㄩ: 'ü', ㄚ: 'a', ㄛ: 'o', ㄜ: 'e', ㄝ: 'ê', ㄞ: 'ai',
  ㄟ: 'ei', ㄠ: 'ao', ㄡ: 'ou', ㄢ: 'an', ㄣ: 'en', ㄤ: 'ang', ㄥ: 'eng', ㄦ: 'er',
};
const TONE_COMBINING = { 1: '\u0304', 2: '\u0301', 3: '\u030c', 4: '\u0300' };

const initialPinyin = (ini) => (ZHUYIN_INITIALS.find((x) => x.zhuyin === ini) || {}).pinyin || '';

/** 把聲調符號標在正確的母音上（a > e/ê > o > 最後一個 i/u/ü） */
function addToneMark(py, tone) {
  const mark = TONE_COMBINING[tone];
  if (!mark) return py; // 輕聲不標
  let idx = -1;
  for (const v of ['a', 'ê', 'e', 'o']) {
    idx = py.indexOf(v);
    if (idx >= 0) break;
  }
  if (idx < 0) {
    for (let k = py.length - 1; k >= 0; k--) {
      if ('iuü'.includes(py[k])) { idx = k; break; }
    }
  }
  if (idx < 0) return py;
  return (py.slice(0, idx + 1) + mark + py.slice(idx + 1)).normalize('NFC');
}

/** 注音書寫：一聲不標、二三四聲標在字尾、輕聲的點寫在字首 */
export function formatZhuyin(ini, fin, toneId) {
  const tone = TONE_MARKS.find((t) => t.id === String(toneId)) || TONE_MARKS[0];
  const body = `${ini}${fin}`;
  return tone.id === '5' ? `˙${body}` : `${body}${tone.mark}`;
}

/** 漢語拼音（含正確的拼寫規則與聲調符號），例：ㄋㄞ + 三聲 → nǎi */
export function toPinyin(ini, fin, toneId) {
  let py;
  if (!ini) {
    py = { ㄧ: 'yi', ㄨ: 'wu', ㄩ: 'yu' }[fin] || FINAL_PINYIN[fin] || '';
  } else if (!fin) {
    py = initialPinyin(ini) + (EMPTY_RHYME_INITIALS.includes(ini) ? 'i' : '');
  } else if (['ㄐ', 'ㄑ', 'ㄒ'].includes(ini) && fin === 'ㄩ') {
    py = initialPinyin(ini) + 'u'; // ju qu xu（ü 上的兩點省略）
  } else {
    py = initialPinyin(ini) + FINAL_PINYIN[fin];
  }
  return addToneMark(py, Number(toneId));
}

const symbolList = (arr) => arr.join(' ');
const finalsAfter = (ini) =>
  ZHUYIN_FINALS.map((f) => f.zhuyin).filter((f) => SYLLABLES[ini + f]);
const initialsBefore = (fin) =>
  ZHUYIN_INITIALS.map((i) => i.zhuyin).filter((i) => SYLLABLES[i + fin]);

/** 不合法組合的原因（給學習者看的文字） */
export function explainIllegal(ini, fin) {
  if (!ini && !fin) return '請先選一個聲母或韻母。';
  if (!fin) return `「${ini}」是聲母，只有聲音的開頭，後面要接韻母才唸得完整。`;
  if (!ini) return `「${fin}」不能單獨成音，前面要接聲母。`;
  if (fin === 'ㄦ') return 'ㄦ 是捲舌韻母，不和聲母相拼，只能單獨唸成「兒」。';
  if (EMPTY_RHYME_INITIALS.includes(ini) && fin === 'ㄧ') {
    return `${ini} 本身就帶著 ㄧ 的聲音（單獨唸就是 ${toPinyin(ini, '', 1)}），所以不能再接 ㄧ。把韻母改成「無」就能聽到它的音了。`;
  }
  if (['ㄐ', 'ㄑ', 'ㄒ'].includes(ini)) {
    return `${ini} 後面只能接 ㄧ、ㄩ（或以 ㄧ、ㄩ 開頭的韻母），沒有「${ini}${fin}」這個音。`;
  }
  if (fin === 'ㄝ') return 'ㄝ 不會直接接在聲母後面，要先接 ㄧ 或 ㄩ（例如 ㄧㄝ、ㄩㄝ）才成音。';
  if (fin === 'ㄩ') return `ㄩ 只能接在 ${symbolList(initialsBefore('ㄩ'))} 後面，沒有「${ini}${fin}」這個音。`;
  const afterList = finalsAfter(ini);
  if (afterList.length) {
    return `國語裡沒有「${ini}${fin}」這個音。${ini} 後面能接的韻母有：${symbolList(afterList)}。`;
  }
  return `國語裡沒有「${ini}${fin}」這個音。`;
}

/**
 * 查詢一個組合。回傳：
 *  - status 'empty'     ：聲母韻母都沒選
 *  - status 'illegal'   ：念不出來的組合（reason 說明原因）
 *  - status 'no-sample' ：合法音節，但這個聲調沒有可靠的示範字／詞（reason 說明）
 *  - status 'ok'        ：text 是要朗讀的字／詞，audioKey 是預錄音檔的檔名
 */
export function lookupSyllable(ini, fin, toneId) {
  const tone = Number(toneId) || 1;
  const base = {
    zhuyin: formatZhuyin(ini, fin, tone),
    pinyin: toPinyin(ini, fin, tone),
  };
  if (!ini && !fin) return { ...base, status: 'empty', reason: explainIllegal(ini, fin) };

  const row = SYLLABLES[`${ini}${fin}`];
  if (!row) return { ...base, status: 'illegal', reason: explainIllegal(ini, fin) };

  const text = row[tone - 1];
  if (!text) {
    const hasTone = row.slice(0, 4).some(Boolean);
    let reason;
    if (tone === 5) {
      reason = '輕聲是詞語裡又輕又短的音，這個組合我們沒有收錄示範詞，所以先不播放。';
    } else if (hasTone) {
      reason = '這是合法的音節，但這個聲調沒有常用字可以示範，所以先不播放。試試別的聲調吧！';
    } else if (row[4]) {
      reason = '這個音節平常只會唸成輕聲，請改選「輕聲」來試聽。';
    } else {
      reason = '這是合法但很少用的音節，我們沒有收錄示範字，所以先不播放。';
    }
    return { ...base, status: 'no-sample', reason };
  }
  return { ...base, status: 'ok', text, audioKey: `${ini}${fin}${tone}`, isWord: tone === 5 };
}
